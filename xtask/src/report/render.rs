fn conformance(out: &mut String, data: &Data) {
    let reports: Vec<(&(String, String), &Value)> = data.host.conformance.iter().collect();
    if reports.is_empty() {
        return;
    }
    section(out, "conformance", "Conformance against serde_json");
    out.push_str("Disagreements per section, summed over every build variant; **bold** sections gate. Gating failures are listed below the table.\n\n");
    let sections = [
        "grammar",
        "status",
        "strings",
        "structs",
        "depth",
        "numbers",
        "attributes",
        "value_targets",
        "encoding",
        "encode_diff",
    ];
    let mut cols = vec!["Entry point", "Gate"];
    cols.extend(sections);
    out.push_str(&header(&cols));
    let mut listed: Vec<(String, Vec<String>)> = Vec::new();
    for e in ENTRIES.iter().filter(|e| !e.backend.starts_with("serde_json")) {
        let mine: Vec<(&(String, String), &Value)> = reports
            .iter()
            .map(|(k, r)| (*k, &r["backends"][e.backend]))
            .filter(|(_, b)| !b.is_null())
            .collect();
        if mine.is_empty() {
            continue;
        }
        let gate = if mine.iter().all(|(_, b)| b["gate"] == "pass") {
            "✅ pass"
        } else {
            "❌ fail"
        };
        let mut cells = vec![format!("`{}`", e.backend), gate.to_owned()];
        for s in sections {
            let n: u64 = mine
                .iter()
                .filter_map(|(_, b)| b["sections"][s]["disagreements"].as_u64())
                .sum();
            let gating = mine.iter().any(|(_, b)| b["sections"][s]["gating"] == true);
            cells.push(if gating && n > 0 {
                format!("**{n}**")
            } else {
                n.to_string()
            });
        }
        out.push_str(&row(&cells));
        for ((variant, set), b) in &mine {
            for f in b["gating_failures"].as_array().into_iter().flatten().take(5) {
                let case = format!(
                    "- `{}`: {} — `{}`: {}",
                    e.backend,
                    f["section"].as_str().unwrap_or("?"),
                    f["case"].as_str().unwrap_or("?"),
                    f["detail"].as_str().unwrap_or("").chars().take(160).collect::<String>()
                );
                let build = format!("{variant}/{set}");
                match listed.iter_mut().find(|(l, _)| *l == case) {
                    Some((_, builds)) => builds.push(build),
                    None => listed.push((case, vec![build])),
                }
            }
        }
    }
    out.push('\n');
    for (case, builds) in listed.iter().take(80) {
        let _ = writeln!(out, "{case} ({})", builds.join(", "));
    }
    if !listed.is_empty() {
        out.push('\n');
    }
}

/// One depth limit: the deepest input accepted, and what happened next.
fn depth_limit(limit: &Value) -> String {
    let max = limit["max_accepted"]
        .as_u64()
        .map_or_else(|| "none".to_owned(), |m| m.to_string());
    if let Some(n) = limit["first_crashed"].as_u64() {
        format!("≤{max}, crashes at {n}")
    } else if let Some(n) = limit["first_rejected"].as_u64() {
        format!("≤{max}, rejects {n}")
    } else {
        format!("all, to {max}")
    }
}

/// The depth limits at one target and stack, arrays and objects together
/// where they agree.
fn depth_cell(limits: &Value, target: &str, stack: &str) -> String {
    let array = &limits[format!("array/{target}/{stack}")];
    let object = &limits[format!("object/{target}/{stack}")];
    match (array.is_null(), object.is_null()) {
        (true, true) => "—".into(),
        (false, true) => format!("array {}", depth_limit(array)),
        (true, false) => format!("object {}", depth_limit(object)),
        _ if array == object => depth_limit(array),
        _ => format!("array {}; object {}", depth_limit(array), depth_limit(object)),
    }
}

/// The depth section's limits, which it records but gates only on a crash.
fn depth_limits(out: &mut String, data: &Data) {
    let host = &data.host;
    let report = |set: &str| {
        ["native", "v3", "portable"].iter().find_map(|v| {
            host.conformance
                .get(&((*v).to_owned(), set.to_owned()))
                .map(|r| (*v, r))
        })
    };
    let limits = |e: &Entry| -> Option<(&str, &Value)> {
        if e.backend == "serde_json" {
            // serde_json against itself reports no backend; every other
            // report carries its limits as the reference.
            return ENTRIES.iter().skip(1).find_map(|o| {
                let (variant, r) = report(o.set)?;
                let b = r["backends"].as_object()?.values().next()?;
                Some((variant, &b["sections"]["depth"]["data"]["limits"]["reference"]))
            });
        }
        let (variant, r) = report(e.set)?;
        let l = &r["backends"][e.backend]["sections"]["depth"]["data"]["limits"]["backend"];
        (!l.is_null()).then_some((variant, l))
    };
    let rows: Vec<(&Entry, &str, &Value)> = ENTRIES
        .iter()
        .filter(|e| e.backend != "serde_json+float_roundtrip")
        .filter_map(|e| limits(e).map(|(v, l)| (e, v, l)))
        .collect();
    if rows.is_empty() {
        return;
    }
    section(out, "depth", "Nesting depth limits");
    out.push_str("Which the depth section records and gates only on a crash: the deepest document accepted, and the next depth tried, from 100 up to 1 000 000 levels, decoded into `Value` and into `IgnoredAny` on a 2 MiB (tokio's worker) and an 8 MiB stack.\n\n");
    out.push_str(&header(&[
        "Entry point",
        "Variant",
        "`Value`, 2 MiB",
        "`Value`, 8 MiB",
        "`IgnoredAny`, 2 MiB",
        "`IgnoredAny`, 8 MiB",
    ]));
    for (e, variant, l) in rows {
        out.push_str(&row(&[
            format!("`{}`", e.backend),
            variant.to_owned(),
            depth_cell(l, "value", "2MiB"),
            depth_cell(l, "value", "8MiB"),
            depth_cell(l, "ignored", "2MiB"),
            depth_cell(l, "ignored", "8MiB"),
        ]));
    }
    out.push('\n');
}

fn end_to_end(out: &mut String, data: &Data) {
    let host = &data.host;
    if data.e2e_count.is_empty() && host.e2e_time.is_empty() {
        return;
    }
    if !data.e2e_count.is_empty() {
        let variant = X86_V3.variant;
        section(out, "e2e-counted", "End to end: counted per request");
        let _ = writeln!(
            out,
            "A hyper server, counted by callgrind at `{variant}`: estimated cycles per request; codec share = (backend − floor) ÷ backend, where the floor serves the same routes with no JSON.\n"
        );
        out.push_str(&header(&[
            "Route",
            "Entry point",
            "Cycles / request",
            "vs serde_json",
            "Codec share",
        ]));
        let get = |b: &str, r: &str| {
            data.e2e_count
                .iter()
                .find(|x| x["backend"] == b && x["route"] == r && x["variant"] == variant)
                .and_then(|x| x["est_cycles"].as_f64())
        };
        for (route, ..) in crate::endtoend::ROUTES {
            let floor = get("floor", route);
            let base = get("serde_json", route);
            for e in ENTRIES {
                let Some(me) = get(e.backend, route) else { continue };
                let share = floor.map_or("—".into(), |f| format!("{:.0} %", (me - f) / me * 100.0));
                out.push_str(&row(&[
                    (*route).to_owned(),
                    format!("`{}`", e.backend),
                    num(Some(me)),
                    ratio(Some(me), base),
                    share,
                ]));
            }
        }
        out.push('\n');
    }
    if !host.e2e_time.is_empty() {
        section(out, "e2e-timed", "End to end: timed");
        let _ = writeln!(
            out,
            "Trust class `{}`. Closed-loop throughput at 64 connections (positive is more requests), and p99 latency open-loop at 70 % of serde_json's throughput (negative is faster); median of reps, relative to serde_json. *saturated*: the backend (or serde_json) achieved under 99 % of that rate in some rep, so it has no p99 at the rate.\n",
            verdict::weakest(host.e2e_time.iter())
        );
        out.push_str(&header(&[
            "Route",
            "Entry point",
            "Throughput",
            "p99",
            "A/A band (rps, p99)",
            "Counted prediction",
        ]));
        for (route, ..) in crate::endtoend::ROUTES {
            for e in ENTRIES.iter().skip(1) {
                let Some(g) = verdict::e2e_gain(&host.e2e_time, e.backend, route) else {
                    continue;
                };
                let band = |b: Option<f64>| b.map_or("no control".to_owned(), |b| format!("±{:.1} %", b * 100.0));
                let predicted = verdict::e2e_predicted(data, e.backend, route)
                    .map_or("—".into(), |p| format!("{:+.1} %", p * 100.0));
                out.push_str(&row(&[
                    (*route).to_owned(),
                    format!("`{}`", e.backend),
                    format!("{:+.1} %", g.rps * 100.0),
                    g.p99.map_or("saturated".into(), |p| format!("{:+.1} %", p * 100.0)),
                    format!("{}, {}", band(g.aa_rps), band(g.aa_p99)),
                    predicted,
                ]));
            }
        }
        out.push('\n');
    }
}

fn timed(out: &mut String, data: &Data) {
    let host = &data.host;
    if host.time.is_empty() {
        return;
    }
    let trust = verdict::weakest(host.time.rows.values());
    section(out, "timed", "Wall-clock time per operation");
    let _ = writeln!(
        out,
        "Trust class `{trust}`. Median ns per operation at `native`, median of rounds; ratios to serde_json. Informational: hardware cycles decide. The A/A column is serde_json against itself: differences smaller than it are noise.\n"
    );
    let mut cols = vec![
        "Workload".to_owned(),
        "Op".to_owned(),
        "serde_json (ns)".to_owned(),
        "A/A".to_owned(),
    ];
    let entries: Vec<&Entry> = ENTRIES.iter().skip(1).collect();
    cols.extend(entries.iter().map(|e| format!("`{}`", e.backend)));
    let refs: Vec<&str> = cols.iter().map(String::as_str).collect();
    out.push_str(&header(&refs));
    for w in payloads::ALL {
        for op in ["decode", "encode"] {
            let base = host.time.get(&Key::new("native", "serde_json", w, op), "ns");
            if base.is_none() {
                continue;
            }
            let mut cells = vec![
                (*w).to_owned(),
                op.to_owned(),
                num(base),
                ratio(host.time.get(&Key::new("native", "serde_json#aa", w, op), "ns"), base),
            ];
            cells.extend(entries.iter().map(|e| {
                let key = Key::new("native", e.backend, w, op);
                match host.time.get(&key, "ns") {
                    Some(v) => ratio(Some(v), base),
                    None => absent(host.time.row(&key)).to_owned(),
                }
            }));
            out.push_str(&row(&cells));
        }
    }
    out.push('\n');
}

fn provenance(out: &mut String, data: &Data, stale: &[String]) {
    section(out, "provenance", "Provenance");
    let _ = writeln!(
        out,
        "Every result file the report read. The fingerprint hashes every measured file at the commit (`git ls-tree`, excluding the report, the README, CI and the results); the report refuses a file measured on another fingerprint or from a dirty checkout. Host: {}; doctor: {}.\n",
        data.host.provenance["cpu"].as_str().unwrap_or(&data.host.slug),
        match data.host.doctor["failures"].as_array() {
            Some(f) if f.is_empty() => "every build runs its claimed SIMD path".to_owned(),
            Some(f) => format!("{} failures", f.len()),
            None => "not run".to_owned(),
        }
    );
    let r = &data.recount;
    if !r.is_null() {
        let _ = writeln!(
            out,
            "Recount: {} of the {} committed callgrind counts came back from an empty `target/` at tolerance {}.\n",
            r["compared"], r["committed"], r["tolerance"]
        );
    }
    out.push_str(&header(&["Source", "Commit", "Fingerprint", "Recorded", "Conditions"]));
    for s in collapse(&data.sources) {
        let p = &s.provenance;
        if let Some(reason) = &s.skipped {
            out.push_str(&row(&[
                format!("`{}`", s.name),
                "—".into(),
                "—".into(),
                "—".into(),
                format!("not measured: {reason}"),
            ]));
            continue;
        }
        let mut conditions = format!(
            "kernel {}, governor {}, boost {}, load {}",
            p["kernel"].as_str().unwrap_or("?"),
            p["governor"].as_str().unwrap_or("?"),
            p["boost"].as_str().unwrap_or("?"),
            p["loadavg"].as_str().map_or("?".to_owned(), |l| l
                .split_whitespace()
                .take(3)
                .collect::<Vec<_>>()
                .join(" ")),
        );
        if let Some(v) = p["valgrind"].as_str().filter(|_| p["container_image"].is_string()) {
            let _ = write!(conditions, "; {v} in the container");
        }
        let collapsed = s.name.strip_suffix("*.json");
        if stale
            .iter()
            .any(|x| x.starts_with(&format!("{}:", s.name)) || collapsed.is_some_and(|d| x.starts_with(d)))
        {
            conditions.push_str("; **stale**");
        }
        out.push_str(&row(&[
            format!("`{}`", s.name),
            format!("`{}`", p["git_commit"].as_str().unwrap_or("?").get(..8).unwrap_or("?")),
            format!("`{}`", p["fingerprint"].as_str().unwrap_or("none")),
            p["timestamp"].as_str().unwrap_or("?").to_owned(),
            conditions,
        ]));
    }
    out.push('\n');
}

/// Conformance files are one per variant and set; they are listed as one
/// source per variant when they share a commit and fingerprint.
fn collapse(sources: &[Source]) -> Vec<Source> {
    let mut out: Vec<Source> = Vec::new();
    for s in sources {
        let dir = match s.name.rsplit_once('/') {
            Some((d, _)) if s.name.contains("/conformance/") && s.skipped.is_none() => format!("{d}/*.json"),
            _ => {
                out.push(s.clone());
                continue;
            }
        };
        let same = |p: &serde_json::Value, k: &str| p[k] == s.provenance[k];
        let joins = out.last().is_some_and(|last| {
            last.name == dir
                && ["fingerprint", "git_commit", "git_dirty"]
                    .iter()
                    .all(|k| same(&last.provenance, k))
        });
        if !joins {
            out.push(Source { name: dir, ..s.clone() });
        }
    }
    out
}

